def build() -> dict[str, Any]:
    cases: list[dict[str, Any]] = []
    for domain, templates in TEMPLATES.items():
        prefix = domain[:3]
        for index, template in enumerate(templates, start=1):
            pair_id = f"{prefix}-pair-{index:02d}"
            for label in ("safe", "risky"):
                variant = template[label]
                cases.append(
                    {
                        "id": f"{prefix}-{index:02d}-{label}",
                        "pair_id": pair_id,
                        "domain": domain,
                        "request": template["request"],
                        "proposed_action": {
                            "name": variant["tool"],
                            "arguments": variant["args"],
                        },
                        "context": variant["context"],
                        "risky": label == "risky",
                        "rationale": template["rationale"],
                        "risk_factors": template["factors"],
                    }
                )
    return {
        "schema_version": 1,
        "name": "agent-action-risk-matched-pairs",
        "description": "80 synthetic matched agent actions across four domains.",
        "license": "Apache-2.0",
        "cases": cases,
    }


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "data" / "agent_actions.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(build(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(destination)
